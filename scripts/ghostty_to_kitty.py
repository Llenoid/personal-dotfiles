#!/usr/bin/env python3
"""Ghostty to Kitty Theme Converter.

Converts Ghostty color palettes and theme configurations into Kitty-compatible
.conf theme files. Handles single files or directory trees.
"""

import argparse
import re
import sys
from pathlib import Path
from typing import List, Tuple

# Property translation rules: (Ghostty regex, Kitty replacement)
COLOR_RULES: List[Tuple[re.Pattern, str]] = [
    (re.compile(r"^\s*background\s*=\s*[\"']?([^\"'\s]+)[\"']?"), r"background \1"),
    (re.compile(r"^\s*foreground\s*=\s*[\"']?([^\"'\s]+)[\"']?"), r"foreground \1"),
    (re.compile(r"^\s*cursor-color\s*=\s*[\"']?([^\"'\s]+)[\"']?"), r"cursor \1"),
    (
        re.compile(r"^\s*cursor-text\s*=\s*[\"']?([^\"'\s]+)[\"']?"),
        r"cursor_text_color \1",
    ),
    (
        re.compile(r"^\s*selection-background\s*=\s*[\"']?([^\"'\s]+)[\"']?"),
        r"selection_background \1",
    ),
    (
        re.compile(r"^\s*selection-foreground\s*=\s*[\"']?([^\"'\s]+)[\"']?"),
        r"selection_foreground \1",
    ),
    (
        re.compile(r"^\s*palette\s*=\s*[\"']?([0-9]+)\s*=\s*([^\"'\s]+)[\"']?"),
        r"color\1 \2",
    ),
]


def convert_file(src: Path, dest: Path, force: bool = False) -> bool:
    """Converts a single Ghostty theme file to Kitty format."""
    if dest.exists() and not force:
        print(f"[SKIP] Destination exists: {dest} (use --force to overwrite)")
        return False

    lines = src.read_text(encoding="utf-8").splitlines()
    output: List[str] = [
        f"# Converted from Ghostty theme: {src.name}",
        "# Auto-generated by ghostty_to_kitty.py",
        "",
    ]

    converted_count = 0
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            output.append(line)
            continue

        matched = False
        for pattern, replacement in COLOR_RULES:
            if pattern.match(stripped):
                output.append(pattern.sub(replacement, stripped))
                converted_count += 1
                matched = True
                break

        if not matched:
            # Comment out non-color Ghostty settings (keybinds, shaders, fonts)
            output.append(f"# [ghostty-only] {line}")

    if converted_count == 0:
        print(f"[WARN] No color definitions found in: {src}")
        return False

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"[OK] {src.name} -> {dest}")
    return True


def main() -> None:
    dotfiles_default = Path.home() / "dev" / "dotfiles"
    default_input = dotfiles_default / "ghostty" / "themes"
    default_output = dotfiles_default / "kitty" / "themes" / "ghostty"

    parser = argparse.ArgumentParser(
        description="Batch convert Ghostty themes to Kitty theme files."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=default_input,
        help=f"Input Ghostty theme file or directory (default: {default_input})",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=default_output,
        help=f"Output directory for Kitty themes (default: {default_output})",
    )
    parser.add_argument(
        "-f",
        "--force",
        action="store_true",
        help="Overwrite existing output files",
    )

    args = parser.parse_args()
    input_path: Path = args.input.expanduser().resolve()
    output_dir: Path = args.output.expanduser().resolve()

    if not input_path.exists():
        print(f"Error: Input path '{input_path}' does not exist.", file=sys.stderr)
        sys.exit(1)

    if input_path.is_file():
        out_file = output_dir / (
            input_path.name
            if input_path.name.endswith(".conf")
            else f"{input_path.name}.conf"
        )
        convert_file(input_path, out_file, force=args.force)
    else:
        # Process files inside theme directories and standalone config files
        targets = [
            p
            for p in input_path.rglob("*")
            if p.is_file() and not p.name.startswith(".")
        ]
        if not targets:
            print(f"No theme files found in {input_path}")
            return

        print(f"Found {len(targets)} potential theme files. Converting...")
        success_count = 0
        for src in targets:
            rel_name = src.name if src.name.endswith(".conf") else f"{src.name}.conf"
            dest = output_dir / rel_name
            if convert_file(src, dest, force=args.force):
                success_count += 1

        print(
            f"\nFinished. Successfully converted {success_count}/{len(targets)} themes."
        )


if __name__ == "__main__":
    main()
